import numpy as np
import matplotlib.pyplot as plt

# Solución analítica: y(x) = -3x^2 + 3x + 2
def solucion_analitica(x):
    return -3 * x**2 + 3 * x + 2

# Diferencias finitas
def diferencias_finitas(dx, n_puntos):
    x_vals = [0.0]
    y_vals = [2.0]  # Condición inicial y(0) = 2

    for i in range(n_puntos - 1):
        x_i = x_vals[-1]
        y_i = y_vals[-1]

        # dy/dx = -6x + 3  =>  y_{i+1} = y_i + (-6*x_i + 3) * dx
        pendiente = -6 * x_i + 3
        y_siguiente = y_i + pendiente * dx
        x_siguiente = x_i + dx

        x_vals.append(x_siguiente)
        y_vals.append(y_siguiente)

    return np.array(x_vals), np.array(y_vals)

# Valores de delta del ejercicio
deltas = [0.5, 1, 5, 20]
n_puntos = 20

# figura con subplots
fig, axs = plt.subplots(2, 2, figsize=(12, 10))
axs = axs.flatten()

for i, dx in enumerate(deltas):
    # Calcula puntos por diferencias finitas
    x_fd, y_fd = diferencias_finitas(dx, n_puntos)

    # Genera curva analítica para el mismo rango de x
    x_rango = np.linspace(0, max(x_fd), 500)
    y_analitica = solucion_analitica(x_rango)

    # Grafica
    axs[i].plot(x_rango, y_analitica, label='Solución Analítica', color='blue', lw=2)
    axs[i].scatter(x_fd, y_fd, color='red', label=f'Diferencias Finitas (Δx={dx})', zorder=5)

    axs[i].set_title(f'Comparación con Δx = {dx}')
    axs[i].set_xlabel('x')
    axs[i].set_ylabel('y')
    axs[i].legend()
    axs[i].grid(True, linestyle='--', alpha=0.7)

plt.tight_layout()
plt.show()

"""Discusión de los Resultados:

Al observar las gráficas y el comportamiento de la aproximación, notamos que la aproximación sigue la curva, aunque se nota una ligera desviación acumulada conforme $x$ aumenta. A medida que $\Delta x$ aumenta (1, 5, 20), la distancia entre los puntos rojos y la línea azul se incrementa, ya que este método asume que la pendiente es constante durante todo el intervalo $\Delta x$. Como la solución real es una parábola, su pendiente cambia linealmente en cada punto. Al usar un paso muy grande (como $\Delta x = 20$), se pierde la información de la curvatura y en cada paso la aproximación se aleja un poco más de la solución real, lo que explica la diferencia al final de los 20 puntos en el eje $y$ para valores grandes de delta.
"""

import numpy as np
import matplotlib.pyplot as plt

def solucion_analitica(x):
    return -3 * x**2 + 3 * x + 2

def diferencias_finitas(dx, n_puntos):
    x_vals, y_vals = [0.0], [2.0]
    for i in range(n_puntos - 1):
        y_next = y_vals[-1] + (-6 * x_vals[-1] + 3) * dx
        x_vals.append(x_vals[-1] + dx)
        y_vals.append(y_next)
    return np.array(x_vals), np.array(y_vals)

# Parámetros para el Zoom
dx_zoom = 0.5
puntos_zoom = 6

x_fd, y_fd = diferencias_finitas(dx_zoom, puntos_zoom)
x_cont = np.linspace(0, max(x_fd), 200)
y_cont = solucion_analitica(x_cont)

plt.figure(figsize=(10, 6))
plt.plot(x_cont, y_cont, 'b-', label='Solución Analítica (Real)', lw=2)
plt.scatter(x_fd, y_fd, color='red', s=60, label=f'Diferencias Finitas ($\Delta x={dx_zoom}$)', zorder=5)

# Dibujar líneas de error para visualizar la diferencia
for i in range(len(x_fd)):
    y_real = solucion_analitica(x_fd[i])
    plt.vlines(x_fd[i], y_real, y_fd[i], colors='gray', linestyles='dashed', alpha=0.5)
    plt.text(x_fd[i], y_fd[i]+0.1, f'Error: {abs(y_fd[i]-y_real):.2f}', fontsize=9, ha='center')

plt.title('Zoom: Acumulación de Error en Diferencias Finitas')
plt.xlabel('x')
plt.ylabel('y')
plt.legend()
plt.grid(True, alpha=0.3)
plt.show()

