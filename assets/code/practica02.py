import matplotlib.pyplot as plt
#Definimos una función de crecimiento exponencial con la ecuación en diferencias
#finitas Pn +1 = kPn con k costante.
def crecimiento_exponencial(k : float, n : int):
    Puntos = [2]

    for i in range(n):
      P = k * Puntos[-1]
      Puntos.append(P)

    return Puntos

#Asignamos los k que queremos ocupar.
pesos = [2, 1, 0.5, -0.5, -1, -2]
n = 100

#Para comprender mejor las ecucaciones en diferencias finitas mostramos una gráfica
#para cada uno de los pesos.
for k in pesos:
    Puntos = crecimiento_exponencial(k, n)
    plt.figure(figsize=(10,6))
    plt.plot(range(len(Puntos)), Puntos, label=f'k={k}')
    plt.title("Crecimiento Exponencial")
    plt.xlabel("n")
    plt.ylabel("P(n)")
    plt.legend()
    plt.grid()
    plt.show()

