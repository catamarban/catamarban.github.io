import matplotlib.pyplot as plt
#Definimos una función de crecimiento logistica con la ecuación en diferencias finitas
#Pn+1 =kPn + r * Pn * (1 - (Pn / K)) con k y r costantes.
def crecimiento_logistico(P0 : int, r : float, K : float, n : int):
    P = [P0]

    for i in range(n):
      #Consideando Delta t = 1
        Pn_siguiente = P[-1] + r * P[-1] * (1 - (P[-1] / K))
        P.append(Pn_siguiente)

    return P

#Asignamos los valores y la lista con las poblaciones iniciales a evaluar.
r = 0.5
K = 1000
n = 40

Poblaciones_iniciales = [5, 1000, 1500]

plt.figure(figsize=(10,6))

#Mostramos las gráficas del crecimiento logistico con todas las poblaciones iniciales.
for P0 in Poblaciones_iniciales:
    P = crecimiento_logistico(P0, r, K, n)
    plt.plot(P, label=f'P0={P0}')
